#!/usr/bin/env python3
"""Validate that an LMCache dry-run uses the LMCache branch, not HiCache."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "server_command",
        type=Path,
        help="Path to server_command.json generated by bench_coding_kvflow_prefetch.py.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    data = json.loads(args.server_command.read_text(encoding="utf-8"))
    cmd = data.get("cmd", [])
    checks = {
        "baseline_profile_is_lmcache": data.get("baseline_profile") == "lmcache",
        "resolved_enable_lmcache": data.get("resolved_server_extra_args") == "--enable-lmcache",
        "cmd_has_enable_lmcache": "--enable-lmcache" in cmd,
        "cmd_has_no_hierarchical_cache": "--enable-hierarchical-cache" not in cmd,
        "cmd_has_no_hicache_prefetch": "--enable-hicache-prefetch" not in cmd,
        "suppressed_hicache": data.get("hierarchical_cache_suppressed_for_lmcache") is True,
        "lmcache_config_present": bool(data.get("lmcache_config")),
    }
    failed = [name for name, ok in checks.items() if not ok]
    print(json.dumps({"checks": checks, "ok": not failed}, indent=2))
    if failed:
        raise SystemExit(f"LMCache preflight failed: {', '.join(failed)}")


if __name__ == "__main__":
    main()
